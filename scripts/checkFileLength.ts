import { readdir, readFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const sourceExtensions = new Set([
  '.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs', '.dart', '.py',
  '.svelte', '.css', '.scss', '.sql', '.prisma'
]);
const scanRoots = ['src', 'apps', 'workers', 'prisma', 'scripts', 'tests'];
const ignoredDirectories = new Set([
  'node_modules', 'dist', '.svelte-kit', '.dart_tool', 'build', 'coverage', 'generated'
]);

async function collectSourceFiles(directory: string): Promise<string[]> {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch {
    return [];
  }

  const nested = await Promise.all(entries.map(async (entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      return ignoredDirectories.has(entry.name) ? [] : collectSourceFiles(path);
    }
    if (!entry.isFile() || !sourceExtensions.has(extensionOf(entry.name))) return [];
    return [path];
  }));

  return nested.flat();
}

function extensionOf(fileName: string): string {
  const separator = fileName.lastIndexOf('.');
  return separator < 0 ? '' : fileName.slice(separator);
}

function countPhysicalLines(source: string): number {
  if (source.length === 0) return 0;
  const lines = source.replace(/\r\n?/g, '\n').split('\n');
  return lines.at(-1) === '' ? lines.length - 1 : lines.length;
}

const files = (await Promise.all(scanRoots.map(collectSourceFiles))).flat().sort();
const violations: string[] = [];

for (const file of files) {
  const source = await readFile(file, 'utf8');
  const segments = file.split(sep);
  const isGeneratedMigration =
    segments[0] === 'prisma' &&
    segments[1] === 'migrations' &&
    file.endsWith('.sql') &&
    source.startsWith('-- Generated by Prisma Migrate (do not edit)');
  if (isGeneratedMigration) continue;
  const lineCount = countPhysicalLines(source);
  if (lineCount > 250) violations.push(`${relative('.', file)}:${lineCount}`);
}

if (violations.length > 0) {
  console.error(`Source files exceed the 250-line limit (${violations.length}):`);
  for (const violation of violations) console.error(`  ${violation}`);
  process.exitCode = 1;
} else {
  console.log(`File-length check passed for ${files.length} source files.`);
}
